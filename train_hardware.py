def _fmt(value):
    text = f"{float(value):.9g}"
    if not any(ch in text for ch in ".en"):
        text += ".0"
    return text + "f"


def export_rf_to_c(clf, path):
    """Export sklearn tree probabilities into the firmware's C API."""
    tree_count = len(clf.estimators_)
    class_count = len(clf.classes_)
    output = ["// Auto-generated by train_hardware.py.", "#pragma once",
              f"#define RF_N_CLASSES {class_count}",
              f"#define RF_N_FEATURES {clf.n_features_in_}", ""]
    for tree_index, estimator in enumerate(clf.estimators_):
        tree = estimator.tree_

        def emit(node, depth):
            pad = "  " * depth
            if tree.children_left[node] == -1:
                values = tree.value[node][0]
                values = values / values.sum()
                return pad + " ".join(
                    f"p[{i}]+={_fmt(values[i])};" for i in range(class_count) if values[i] > 0
                ) + "\n"
            code = f"{pad}if (x[{tree.feature[node]}] <= {_fmt(tree.threshold[node])}) {{\n"
            code += emit(tree.children_left[node], depth + 1)
            code += f"{pad}}} else {{\n"
            code += emit(tree.children_right[node], depth + 1)
            return code + f"{pad}}}\n"

        output.append(f"static void rf_tree_{tree_index}(const float *x, float *p) {{\n{emit(0, 1)}}}\n")
    output.extend(["// returns predicted class; proba[RF_N_CLASSES] receives probabilities",
                   "static int rf_predict(const float *x, float *proba) {"])
    output.append(f"  for (int c = 0; c < {class_count}; c++) proba[c] = 0;")
    output.extend(f"  rf_tree_{i}(x, proba);" for i in range(tree_count))
    output.append(f"  int best = 0;\n  for (int c = 0; c < {class_count}; c++) {{ proba[c] /= {tree_count}.0f; if (proba[c] > proba[best]) best = c; }}")
    output.append("  return best;\n}")
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as stream:
        stream.write("\n".join(output))


MAX_RAW_SAMPLES = 1_000_000
HOP = N // 2
RECORDING_FOLDERS = {
    0: "normal",
    1: "imbalance",
    2: "misalignment",
    3: "bearing",
    4: "bearing_ball",
}
CWRU_FOLDERS = {
    "normal": 0,
    "bearing_outer": 3,
    "bearing_ball": 4,
}


def append_windows(signal, class_id, group, rows, labels, groups):
    count = 0
    for start in range(0, len(signal) - N + 1, HOP):
        rows.append(features(signal[start:start + N]))
        labels.append(class_id)
        groups.append(group)
        count += 1
    return count


def load_recording_windows():
    """Read each recording separately, anti-alias to 1 kHz, then window it."""
    rows, labels, groups = [], [], []
    groups_by_class = {class_id: [] for class_id in range(len(CLASSES))}

    for class_id, folder in RECORDING_FOLDERS.items():
        paths = sorted(glob.glob(os.path.join("data_mafaulda", folder, "*.zip")))
        if not paths:
            raise RuntimeError(f"No recordings found for {CLASSES[class_id]}")

        for path in paths:
            group = f"mafaulda:{class_id}:{os.path.basename(path)}"
            try:
                with zipfile.ZipFile(path) as archive:
                    csv_name = next(n for n in archive.namelist() if n.lower().endswith(".csv"))
                    frame = pd.read_csv(archive.open(csv_name), header=None,
                                        usecols=[1], nrows=MAX_RAW_SAMPLES)
            except Exception as exc:
                raise RuntimeError(f"Could not read accelerometer channel from {path}: {exc}") from exc

            raw = frame.iloc[:, 0].to_numpy(dtype=np.float32)
            # MaFaulDA recordings are sampled at 50 kHz. Anti-alias to the
            # MPU6050 accelerometer's 1 kHz output rate.
            signal = resample_poly(raw, up=1, down=50).astype(np.float32)
            count = append_windows(signal, class_id, group, rows, labels, groups)
            groups_by_class[class_id].append(group)
            print(f"{CLASSES[class_id]:14s} {os.path.basename(path):28s} {count:4d} windows")

    # CWRU contributes independent normal and bearing recordings. Resample its
    # 12 kHz drive-end signal to the same 1 kHz feature rate as the firmware.
    for folder, class_id in CWRU_FOLDERS.items():
        paths = sorted(glob.glob(os.path.join("data_cwru", folder, "*.mat")))
        for path in paths:
            try:
                mat = scipy.io.loadmat(path)
                key = next(k for k in mat if "DE_time" in k)
                raw = np.asarray(mat[key]).reshape(-1).astype(np.float32)
            except Exception as exc:
                raise RuntimeError(f"Could not read drive-end signal from {path}: {exc}") from exc
            signal = resample_poly(raw, up=1, down=12).astype(np.float32)
            group = f"cwru:{class_id}:{os.path.basename(path)}"
            count = append_windows(signal, class_id, group, rows, labels, groups)
            groups_by_class[class_id].append(group)
            print(f"{CLASSES[class_id]:14s} CWRU/{os.path.basename(path):23s} {count:4d} windows")

    rng = np.random.default_rng(42)
    heldout_groups = set()
    for class_id, class_groups in groups_by_class.items():
        if len(class_groups) < 2:
            raise RuntimeError(f"Need at least two independent recordings for {CLASSES[class_id]}")
        heldout_groups.add(class_groups[int(rng.integers(len(class_groups)))])

    return (np.asarray(rows, dtype=np.float32), np.asarray(labels, dtype=np.int64),
            np.asarray(groups), set(heldout_groups))


def build_candidates():
    return [
        RandomForestClassifier(n_estimators=24, max_depth=8, min_samples_leaf=3,
                               max_features="sqrt", class_weight="balanced_subsample",
                               random_state=42, n_jobs=1),
        RandomForestClassifier(n_estimators=32, max_depth=10, min_samples_leaf=4,
                               max_features="sqrt", class_weight="balanced_subsample",
                               random_state=42, n_jobs=1),
        RandomForestClassifier(n_estimators=24, max_depth=8, min_samples_leaf=3,
                               max_features="sqrt", class_weight={0: 1, 1: 2, 2: 1, 3: 1, 4: 1},
                               random_state=43, n_jobs=1),
        RandomForestClassifier(n_estimators=24, max_depth=8, min_samples_leaf=3,
                               max_features="sqrt", class_weight={0: 1, 1: 4, 2: 1, 3: 1, 4: 1},
                               random_state=44, n_jobs=1),
        ExtraTreesClassifier(n_estimators=16, max_depth=8, min_samples_leaf=4,
                             max_features="sqrt", class_weight="balanced",
                             random_state=42, n_jobs=1),
        ExtraTreesClassifier(n_estimators=24, max_depth=10, min_samples_leaf=4,
                             max_features="sqrt", class_weight="balanced",
                             random_state=42, n_jobs=1),
    ]


def augment_sensor_gain(X, y, groups, seed):
    """Add gain-varied copies while keeping spectral ratios and shape fixed."""
    rng = np.random.default_rng(seed)
    copies = 2
    augmented = np.repeat(X, copies, axis=0)
    gains = rng.uniform(0.35, 2.8, size=(len(augmented), 1)).astype(np.float32)
    augmented[:, [0, 1, 5]] *= gains
    augmented_groups = np.repeat(groups, copies)
    return (np.concatenate([X, augmented]), np.concatenate([y, np.repeat(y, copies)]),
            np.concatenate([groups, augmented_groups]))


def recording_weights(groups):
    """Give each original recording equal total weight regardless of its length."""
    _, inverse, counts = np.unique(groups, return_inverse=True, return_counts=True)
    weights = 1.0 / counts[inverse]
    return (weights / weights.mean()).astype(np.float32)


def main():
    os.makedirs("results", exist_ok=True)
    X, y, groups, heldout_groups = load_recording_windows()
    is_test = np.isin(groups, list(heldout_groups))
    X_train, y_train, g_train = X[~is_test], y[~is_test], groups[~is_test]
    X_test, y_test = X[is_test], y[is_test]
    if set(np.unique(y_train)) != set(range(len(CLASSES))) or set(np.unique(y_test)) != set(range(len(CLASSES))):
        raise RuntimeError("Every class must appear in both training recordings and held-out recordings.")

    print(f"\nWindows: {len(X)} total; {len(X_train)} train; {len(X_test)} held-out")
    print("Held-out recordings:", ", ".join(sorted(heldout_groups)))
    cv = StratifiedGroupKFold(n_splits=3, shuffle=True, random_state=42)
    best_model, best_cv = None, -1.0
    for candidate in build_candidates():
        scores = []
        for fold, (fit_indices, val_indices) in enumerate(cv.split(X_train, y_train, groups=g_train)):
            fold_model = clone(candidate)
            fold_X, fold_y, fold_groups = augment_sensor_gain(
                X_train[fit_indices], y_train[fit_indices], g_train[fit_indices], 100 + fold)
            fold_model.fit(fold_X, fold_y, sample_weight=recording_weights(fold_groups))
            scores.append(f1_score(y_train[val_indices], fold_model.predict(X_train[val_indices]),
                                   average="macro", zero_division=0))
        scores = np.asarray(scores, dtype=np.float32)
        score = float(scores.mean())
        print(f"{candidate.__class__.__name__:12s} trees={len(candidate.estimators) if hasattr(candidate, 'estimators') else candidate.n_estimators:2d} "
              f"depth={candidate.max_depth:2d} leaf={candidate.min_samples_leaf} "
              f"group-CV macro-F1={score:.3f} +/- {scores.std():.3f}")
        if score > best_cv:
            best_model, best_cv = candidate, score

    X_aug, y_aug, groups_aug = augment_sensor_gain(X_train, y_train, g_train, 42)
    best_model.fit(X_aug, y_aug, sample_weight=recording_weights(groups_aug))
    pred = best_model.predict(X_test)
    print(f"\nRecording-held-out accuracy: {accuracy_score(y_test, pred):.3f}")
    print(f"Recording-held-out macro-F1: {f1_score(y_test, pred, average='macro'):.3f}")
    print(classification_report(y_test, pred, labels=np.arange(len(CLASSES)),
                                target_names=CLASSES, digits=3, zero_division=0))

    disp = ConfusionMatrixDisplay.from_predictions(
        y_test, pred, labels=np.arange(len(CLASSES)), display_labels=CLASSES,
        xticks_rotation=35, cmap="Blues", normalize="true")
    disp.ax_.set_title("Held-out MaFaulDA recordings (normalized)")
    plt.tight_layout()
    plt.savefig("results/confusion_matrix.png", dpi=160)
    plt.close()

    # Fit the selected compact model on all recordings for deployment.
    X_aug, y_aug, groups_aug = augment_sensor_gain(X, y, groups, 43)
    best_model.fit(X_aug, y_aug, sample_weight=recording_weights(groups_aug))
    joblib.dump(best_model, "results/model.joblib")
    for path in ("model.h", "sketch/model.h", "esp32_wokwi/model.h"):
        export_rf_to_c(best_model, path)
    print(f"\nFinal model: {best_model.__class__.__name__}, {len(best_model.estimators_)} trees")
    print(f"C header sizes: root={os.path.getsize('model.h') / 1024:.1f} KB, "
          f"firmware={os.path.getsize('sketch/model.h') / 1024:.1f} KB")


if __name__ == "__main__":
    main()
