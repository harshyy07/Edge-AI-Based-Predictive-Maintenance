"""Train/evaluate the separate servo vibration classifier."""
from __future__ import annotations
import argparse, json
from pathlib import Path
import shutil
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, f1_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.tree import _tree
try:  # package import from the project root
    from .data_loader import load_inputs
    from .features import FEATURE_NAMES, window_table
    from .synthetic_servo import generate_windows
except ImportError:  # direct invocation: python servo_vibration_ml/train.py
    from data_loader import load_inputs
    from features import FEATURE_NAMES, window_table
    from synthetic_servo import generate_windows

ROOT = Path(__file__).resolve().parent


def export_header(model: RandomForestClassifier, path: Path) -> None:
    classes = list(model.classes_)
    trees = []
    for est in model.estimators_:
        tr = est.tree_
        nodes = []
        for i in range(tr.node_count):
            leaf = tr.children_left[i] == _tree.TREE_LEAF
            val = tr.value[i][0]
            pred = int(np.argmax(val)) if leaf else -1
            nodes.append((int(tr.feature[i]), float(tr.threshold[i]), int(tr.children_left[i]), int(tr.children_right[i]), pred))
        trees.append(nodes)
    max_nodes = max(map(len, trees))
    lines = ["// Generated by servo_vibration_ml/train.py. Synthetic-heavy model; see REPORT.md.", "#pragma once", "#include <stdint.h>", f"#define SERVO_RF_TREES {len(trees)}", f"#define SERVO_RF_MAX_NODES {max_nodes}", f"#define SERVO_RF_CLASSES {len(classes)}", f"#define SERVO_RF_FEATURES {len(FEATURE_NAMES)}", "static const char* SERVO_RF_LABELS[] = {" + ", ".join('"'+c+'"' for c in classes) + "};", "typedef struct { int8_t feature; float threshold; int16_t left,right; int8_t prediction; } ServoNode;", "static const ServoNode SERVO_RF[SERVO_RF_TREES][SERVO_RF_MAX_NODES] = {"]
    for nodes in trees:
        lines.append("{")
        for feat, thr, left, right, pred in nodes:
            threshold = f"{thr:.8g}"
            if "." not in threshold and "e" not in threshold.lower():
                threshold += ".0"
            lines.append(f"{{{feat},{threshold}f,{left},{right},{pred}}},")
        lines.append("},")
    lines += ["};", "static inline int servo_rf_predict(const float *x) {", "  int votes[SERVO_RF_CLASSES] = {0};", "  for (int t=0;t<SERVO_RF_TREES;t++) { int n=0;", "    for (int step=0;step<SERVO_RF_MAX_NODES;step++) { const ServoNode *p=&SERVO_RF[t][n];", "      if (p->prediction>=0) { votes[p->prediction]++; break; }", "      n = (x[p->feature] <= p->threshold) ? p->left : p->right;", "    }", "  }", "  int best=0; for(int c=1;c<SERVO_RF_CLASSES;c++) if(votes[c]>votes[best]) best=c; return best;", "}", "// Feature order: " + ", ".join(FEATURE_NAMES)]
    path.write_text("\n".join(lines)+"\n", encoding="utf-8")


def main() -> None:
    ap=argparse.ArgumentParser()
    ap.add_argument("--csv", nargs="*", default=None, help="Labeled servo MPU6050 CSVs (default: data/servo_phase1_*.csv if present)")
    ap.add_argument("--windows-per-class", type=int, default=50)
    ap.add_argument("--seed", type=int, default=42)
    args=ap.parse_args()
    ROOT.joinpath("results").mkdir(exist_ok=True)
    synth=generate_windows(args.windows_per_class,args.seed)
    csv_paths = args.csv if args.csv is not None else sorted(str(p) for p in (ROOT.parent / "data").glob("servo_phase1_*.csv"))
    real=load_inputs(csv_paths)
    samples=pd.concat([synth,real],ignore_index=True) if len(real) else synth
    windows=window_table(samples)
    if windows.empty or windows.label.nunique()<2: raise SystemExit("Need at least two represented labels with complete windows.")
    # Hold out whole independently generated trials / recordings; no window leakage.
    split=GroupShuffleSplit(n_splits=1,test_size=.25,random_state=args.seed)
    train_i,test_i=next(split.split(windows[FEATURE_NAMES],windows.label,windows.group_id))
    tr,te=windows.iloc[train_i],windows.iloc[test_i]
    model=RandomForestClassifier(n_estimators=64,max_depth=8,min_samples_leaf=2,class_weight="balanced",random_state=args.seed,n_jobs=-1)
    model.fit(tr[FEATURE_NAMES],tr.label)
    pred=model.predict(te[FEATURE_NAMES])
    labels=sorted(set(windows.label))
    metrics={"evaluation_scope":"synthetic evaluation; not real-fault validation" if (windows.provenance=="real_servo_csv").sum()==0 else "mixed synthetic/real grouped holdout; real-fault validation still requires independent trials", "sampling_hz":200,"window_samples":200,"feature_names":FEATURE_NAMES,"train_windows":len(tr),"test_windows":len(te),"train_groups":int(tr.group_id.nunique()),"test_groups":int(te.group_id.nunique()),"provenance_counts":windows.provenance.value_counts().to_dict(),"accuracy":float(accuracy_score(te.label,pred)),"macro_f1":float(f1_score(te.label,pred,average="macro")),"classification_report":classification_report(te.label,pred,labels=labels,output_dict=True,zero_division=0)}
    (ROOT/"results"/"metrics.json").write_text(json.dumps(metrics,indent=2)+"\n",encoding="utf-8")
    pd.DataFrame(confusion_matrix(te.label,pred,labels=labels),index=labels,columns=labels).to_csv(ROOT/"results"/"confusion_matrix.csv")
    fig,ax=plt.subplots(figsize=(8,7)); from sklearn.metrics import ConfusionMatrixDisplay
    ConfusionMatrixDisplay.from_predictions(te.label,pred,labels=labels,display_labels=labels,xticks_rotation=40,ax=ax,cmap="Blues"); fig.tight_layout(); fig.savefig(ROOT/"results"/"confusion_matrix.png",dpi=140); plt.close(fig)
    import joblib
    joblib.dump(model,ROOT/"results"/"servo_rf.joblib")
    header_path=ROOT/"model.h"
    export_header(model,header_path)
    esp32_dir=ROOT/"esp32"
    esp32_dir.mkdir(exist_ok=True)
    shutil.copyfile(header_path,esp32_dir/"model.h")
    print(json.dumps({k:metrics[k] for k in ("evaluation_scope","train_windows","test_windows","accuracy","macro_f1","provenance_counts")},indent=2))

if __name__=="__main__": main()
